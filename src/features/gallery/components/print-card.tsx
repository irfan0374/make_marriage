'use client';

import { ArrowLeft, Printer } from 'lucide-react';
import Link from 'next/link';
import { useEffect, useState } from 'react';
import { APP_NAME } from '@/config/app';
import { formatFullDate } from '@/shared/dates';
import { qrUrl } from '../api';
import { useGallery } from '../hooks';

// An A5 card with the couple's names, the gallery QR code and its short link. The browser's
// print dialog opens once the code has loaded; "Save as PDF" there gives a PDF.

const bareUrl = (url: string) => url.replace(/^https?:\/\//, '');

export function PrintCard({
  weddingId,
  brideName,
  groomName,
  weddingDate,
}: {
  weddingId: string;
  brideName: string;
  groomName: string;
  weddingDate: string;
}) {
  const { data: gallery } = useGallery(weddingId);
  const [qrLoaded, setQrLoaded] = useState(false);

  useEffect(() => {
    if (gallery && qrLoaded) {
      const timer = setTimeout(() => window.print(), 300);
      return () => clearTimeout(timer);
    }
  }, [gallery, qrLoaded]);

  return (
    <div className="bg-background-alt flex min-h-screen flex-col items-center gap-6 py-8 print:block print:bg-white print:p-0">
      <style>{'@page { size: A5 portrait; margin: 0; }'}</style>
      <div className="flex items-center gap-3 print:hidden">
        <Link
          href={`/app/${weddingId}/gallery`}
          className="text-text-muted hover:text-text inline-flex items-center gap-1 text-sm font-medium"
        >
          <ArrowLeft aria-hidden className="size-4" />
          Back to gallery
        </Link>
        <button
          type="button"
          onClick={() => window.print()}
          className="bg-primary text-primary-foreground inline-flex items-center gap-1.5 rounded-full px-5 py-2 text-sm font-medium"
        >
          <Printer aria-hidden className="size-4" />
          Print or save as PDF
        </button>
      </div>

      <article className="bg-surface flex h-[210mm] w-[148mm] flex-col items-center justify-between px-[14mm] py-[16mm] text-center shadow-xl print:shadow-none">
        <div className="flex flex-col items-center">
          <span className="text-gold-deep text-[9pt] font-semibold tracking-[0.3em] uppercase">
            Photo gallery
          </span>
          <h1 className="text-primary mt-[4mm] text-[26pt] leading-tight">
            {brideName} <span className="text-gold italic">&amp;</span> {groomName}
          </h1>
          <p className="text-text-muted font-heading mt-[2mm] text-[12pt] italic">
            {formatFullDate(weddingDate)}
          </p>
          <div className="bg-gold mt-[6mm] h-px w-[20mm]" />
        </div>

        <div className="flex flex-col items-center">
          <p className="text-primary font-heading text-[18pt]">Share your photos with us</p>
          <p className="text-text-muted mt-[2mm] max-w-[100mm] text-[10pt] leading-snug">
            Scan with your phone camera to add the moments you captured. No app or sign-up needed.
          </p>
          <div className="border-border mt-[7mm] rounded-[4mm] border p-[3mm]">
            {/* eslint-disable-next-line @next/next/no-img-element -- generated by our API */}
            <img
              src={qrUrl(weddingId, 'svg')}
              alt="QR code for the photo gallery"
              onLoad={() => setQrLoaded(true)}
              className="size-[62mm]"
            />
          </div>
          {gallery && (
            <p className="text-text mt-[4mm] font-mono text-[8.5pt] break-all">
              {bareUrl(gallery.url)}
            </p>
          )}
        </div>

        <p className="text-text-muted text-[7.5pt] tracking-wider uppercase">
          Made with {APP_NAME}
        </p>
      </article>
    </div>
  );
}
